using AvaloniaEdit.Document;
using ScriptArt.Compiler;
using ScriptArt.Compiler.Emit;
using ScriptArt.Compiler.Nodes;
using ScriptArt.GraphModel;
using ScriptArt.NodeEditor;
using ScriptArt.ProjectSystem;
using ScriptArt.ProjectSystem.Debugging;

namespace ScriptArt.App;

/// <summary>
/// The open project and the graph being edited. Each graph keeps its own editor, so undo history survives switching graphs.
/// The entry graph is opened on load. Handwritten C# files opened in the code view keep their text, and its undo history, until
/// saved with the project; node breakpoints last for the session.
/// </summary>
internal sealed class Workspace
{
    private readonly Dictionary<GraphDocument, GraphEditor> editors = [];

    // Handwritten files opened in the code view, by full path, with the text last saved.
    private readonly Dictionary<string, (TextDocument Document, string SavedText)> codeFiles = new(StringComparer.OrdinalIgnoreCase);

    private readonly HashSet<NodeBreakpoint> breakpoints = [];

    // Adding a graph changes the project file, which no graph editor's undo history covers.
    private bool projectChanged;

    // Referenced assemblies whose methods are in the node library.
    private readonly HashSet<string> loadedReferences = new(StringComparer.OrdinalIgnoreCase);

    // How often each graph has changed through its editor, and the copy made for background work at that version. Graphs change
    // only through their editors, so an unchanged version means the copy is still current and is reused (D-041).
    private readonly Dictionary<GraphDocument, int> versions = [];
    private readonly Dictionary<GraphDocument, (int Version, GraphDocument Copy)> copies = [];

    // Identifies the latest compilation of the open graph; a background compilation that finishes after a newer one started is dropped.
    private int compileRequest;

    private Workspace(VisualProject project, GraphCompiler compiler)
    {
        Project = project;
        Compiler = compiler;
        Graph = project.Graphs.FirstOrDefault(graph => graph.Graph.Kind == GraphKind.EntryPoint) ?? project.Graphs[0];
        Editor = EditorFor(Graph);
        LastCompilation = Compile();
        RefreshFiles();
    }

    public VisualProject Project { get; }

    public GraphCompiler Compiler { get; }

    public ProjectGraph Graph { get; private set; }

    public GraphEditor Editor { get; private set; }

    /// <summary>True when a graph, the project file, or an open handwritten file has changes that are not saved.</summary>
    public bool IsDirty => projectChanged || editors.Values.Any(editor => editor.IsDirty) || UnsavedFiles.Count > 0;

    /// <summary>The handwritten C# files of the project, as of the last <see cref="RefreshFiles"/>.</summary>
    public IReadOnlyList<string> SourceFiles { get; private set; } = [];

    /// <summary>The project's references, as of the last <see cref="RefreshFiles"/>.</summary>
    public ProjectReferences References { get; private set; } = new([], PackagesNotRestored: false);

    /// <summary>The project's solution file, as of the last <see cref="RefreshFiles"/>.</summary>
    public string? Solution { get; private set; }

    /// <summary>The code generated by the last successful generation, which debugging maps breakpoints through.</summary>
    public IReadOnlyList<GeneratedSource> GeneratedSources { get; set; } = [];

    /// <summary>The text of open handwritten files that differs from the file on disk, by full path.</summary>
    public IReadOnlyDictionary<string, string> UnsavedFiles => codeFiles
        .Where(file => file.Value.Document.Text != file.Value.SavedText)
        .ToDictionary(file => file.Key, file => file.Value.Document.Text, StringComparer.OrdinalIgnoreCase);

    /// <summary>Every node breakpoint in the project.</summary>
    public IReadOnlySet<NodeBreakpoint> Breakpoints => breakpoints;

    /// <summary>The nodes of the open graph that have a breakpoint.</summary>
    public IReadOnlySet<string> OpenGraphBreakpoints =>
        breakpoints.Where(breakpoint => breakpoint.GraphId == Graph.Graph.Id).Select(breakpoint => breakpoint.NodeId).ToHashSet(StringComparer.Ordinal);

    /// <summary>Adds or removes a breakpoint on a node of the open graph. Returns true when the node now has one.</summary>
    public bool ToggleBreakpoint(string nodeId)
    {
        var breakpoint = new NodeBreakpoint(Graph.Graph.Id, nodeId);
        if (breakpoints.Remove(breakpoint))
        {
            return false;
        }

        breakpoints.Add(breakpoint);
        return true;
    }

    public void ClearBreakpoints() => breakpoints.Clear();

    /// <summary>Re-reads the handwritten files, references, and solution from disk, which other tools can change.</summary>
    public void RefreshFiles()
    {
        SourceFiles = [.. Project.HandwrittenSources()];
        References = Project.References;
        Solution = ProjectSolution.Find(Project);
        breakpoints.RemoveWhere(breakpoint => !Project.Graphs.Any(graph => graph.Graph.Id == breakpoint.GraphId && graph.Graph.FindNode(breakpoint.NodeId) is not null));
    }

    /// <summary>The document of a handwritten file, read from disk the first time it is opened.</summary>
    public TextDocument OpenCodeFile(string path)
    {
        string fullPath = Path.GetFullPath(path);
        if (!codeFiles.TryGetValue(fullPath, out (TextDocument Document, string SavedText) file))
        {
            string text = File.ReadAllText(fullPath);
            file = (new TextDocument(text) { FileName = fullPath }, text);
            file.Document.UndoStack.ClearAll();
            codeFiles.Add(fullPath, file);
        }

        return file.Document;
    }

    /// <summary>True when the open handwritten file <paramref name="path"/> has changes that are not saved.</summary>
    public bool IsCodeFileDirty(string path) => codeFiles.TryGetValue(Path.GetFullPath(path), out (TextDocument Document, string SavedText) file) && file.Document.Text != file.SavedText;

    /// <summary>Node libraries' nodes that could not be added, such as nodes whose type ID another library already uses.</summary>
    public IReadOnlyList<string> LibraryProblems { get; private init; } = [];

    /// <summary>The latest in-memory compilation of the open graph. Updated by <see cref="Compile"/>.</summary>
    public GraphCompilationResult LastCompilation { get; private set; }

    /// <summary>Raised when any graph's editor changes, including graphs that are not open.</summary>
    public event EventHandler? Changed;

    /// <summary>Opens <paramref name="project"/> with the built-in nodes, its references' methods, and the nodes of <paramref name="nodeLibraries"/>.</summary>
    public static Workspace Open(VisualProject project, IReadOnlyList<NodeLibraryContents>? nodeLibraries = null)
    {
        ArgumentNullException.ThrowIfNull(project);
        if (project.Graphs.Count == 0)
        {
            throw new InvalidOperationException($"Project '{project.Name}' contains no graphs.");
        }

        IReadOnlyList<string> references = project.References.AssemblyPaths;
        NodeLibrary library = NodeLibrary.CreateDefault(references);
        List<string> problems = [];
        foreach (NodeLibraryContents contents in nodeLibraries ?? [])
        {
            problems.AddRange(library.RegisterLibrary(contents));
        }

        var workspace = new Workspace(project, new GraphCompiler(library)) { LibraryProblems = problems };
        workspace.loadedReferences.UnionWith(references);
        return workspace;
    }

    /// <summary>
    /// Adds the methods of assemblies the project started referencing since they were last loaded, for example after a build
    /// restored a new package. Returns true when nodes were added. Removed references keep their nodes until the project is reopened.
    /// </summary>
    public bool LoadNewReferences()
    {
        string[] added = [.. Project.References.AssemblyPaths.Where(path => !loadedReferences.Contains(path))];
        if (added.Length == 0)
        {
            return false;
        }

        Compiler.Library.RegisterExternal(ExternalApi.FromAssemblies(added));
        loadedReferences.UnionWith(added);
        return true;
    }

    /// <summary>Makes <paramref name="graph"/> the graph being edited and compiles it.</summary>
    public void OpenGraph(ProjectGraph graph)
    {
        ArgumentNullException.ThrowIfNull(graph);
        Graph = graph;
        Editor = EditorFor(graph);
        Compile();
    }

    /// <summary>Adds a function graph with an unused name such as <c>Function1</c> and opens it.</summary>
    public ProjectGraph AddFunction() => Add(Project.AddFunction(UnusedName("Function")));

    /// <summary>Adds a class or struct graph with an unused name such as <c>Class1</c> and opens it.</summary>
    public ProjectGraph AddType(GraphKind kind) => Add(Project.AddType(UnusedName(kind.ToString()), kind));

    /// <summary>Adds a method with an unused name such as <c>Method1</c> to the class or struct <paramref name="owner"/> and opens it.</summary>
    public ProjectGraph AddMethod(ProjectGraph owner)
    {
        ArgumentNullException.ThrowIfNull(owner);
        return Add(Project.AddMethod(owner.Graph, UnusedName("Method")));
    }

    /// <summary>Adds a constructor with an unused name such as <c>Constructor1</c> to the class or struct <paramref name="owner"/> and opens it.</summary>
    public ProjectGraph AddConstructor(ProjectGraph owner)
    {
        ArgumentNullException.ThrowIfNull(owner);
        return Add(Project.AddConstructor(owner.Graph, UnusedName("Constructor")));
    }

    /// <summary>Renames <paramref name="graph"/> as one step of its own undo history. Its file follows the name on the next save.</summary>
    public void RenameGraph(ProjectGraph graph, string name)
    {
        ArgumentNullException.ThrowIfNull(graph);
        EditorFor(graph).RenameGraph(name);
    }

    /// <summary>
    /// Removes <paramref name="graph"/>, and the methods and constructors of a class or struct, from the project; their files are
    /// deleted by the next save. Opens the program graph when the open graph was removed. This cannot be undone.
    /// </summary>
    public IReadOnlyList<ProjectGraph> RemoveGraph(ProjectGraph graph)
    {
        ArgumentNullException.ThrowIfNull(graph);
        IReadOnlyList<ProjectGraph> removed = Project.RemoveGraph(graph.Graph);
        foreach (ProjectGraph item in removed)
        {
            editors.Remove(item.Graph);
            versions.Remove(item.Graph);
            copies.Remove(item.Graph);
        }

        projectChanged = true;
        IReadOnlyList<GraphDocument> graphs = Project.GraphDocuments;
        foreach (GraphEditor editor in editors.Values)
        {
            editor.ProjectGraphs = graphs;
        }

        OpenGraph(removed.Any(item => item.Graph == Graph.Graph)
            ? Project.Graphs.First(item => item.Graph.Kind == GraphKind.EntryPoint)
            : Project.Graphs.First(item => item.Graph == Graph.Graph));
        return removed;
    }

    private ProjectGraph Add(ProjectGraph added)
    {
        projectChanged = true;
        IReadOnlyList<GraphDocument> graphs = Project.GraphDocuments;
        foreach (GraphEditor editor in editors.Values)
        {
            editor.ProjectGraphs = graphs;
        }

        OpenGraph(added);
        return added;
    }

    private string UnusedName(string prefix) =>
        Enumerable.Range(1, int.MaxValue)
            .Select(number => prefix + number.ToString(System.Globalization.CultureInfo.InvariantCulture))
            .First(candidate => !Project.Graphs.Any(graph =>
                string.Equals(graph.Graph.Name, candidate, StringComparison.OrdinalIgnoreCase)
                || string.Equals(Path.GetFileNameWithoutExtension(Path.GetFileNameWithoutExtension(graph.RelativePath)), candidate, StringComparison.OrdinalIgnoreCase)));

    /// <summary>Compiles the open graph in memory on this thread. Nothing is written to disk.</summary>
    public GraphCompilationResult Compile()
    {
        compileRequest++;
        LastCompilation = Compiler.Compile(Graph.Graph, Project.CompilationOptions, Graph.RelativePath);
        return LastCompilation;
    }

    /// <summary>
    /// Compiles the open graph on a background thread from a snapshot of the project, so editing continues meanwhile. Returns null,
    /// leaving <see cref="LastCompilation"/> alone, when another compilation started before this one finished. Call on the UI thread.
    /// </summary>
    public async Task<GraphCompilationResult?> CompileInBackgroundAsync()
    {
        int request = ++compileRequest;
        VisualProject snapshot = Snapshot();
        ProjectGraph graph = snapshot.Graphs.First(candidate => candidate.Graph.Id == Graph.Graph.Id);
        GraphCompiler compiler = Compiler;
        GraphCompilationResult result = await Task.Run(() => compiler.Compile(graph.Graph, snapshot.CompilationOptions, graph.RelativePath)).ConfigureAwait(true);
        if (request != compileRequest)
        {
            return null;
        }

        LastCompilation = result;
        return result;
    }

    /// <summary>
    /// A read-only copy of the project for compiling, verifying, generating, and navigating on a background thread. Graphs that
    /// have not changed since the last snapshot share their copy with it. Call on the UI thread.
    /// </summary>
    public VisualProject Snapshot() => Project.Snapshot(graph =>
    {
        int version = versions.GetValueOrDefault(graph);
        if (copies.TryGetValue(graph, out (int Version, GraphDocument Copy) copy) && copy.Version == version)
        {
            return copy.Copy;
        }

        GraphDocument fresh = graph.Clone();
        copies[graph] = (version, fresh);
        return fresh;
    });

    public void Save()
    {
        Project.Save();
        projectChanged = false;
        foreach ((string path, string text) in UnsavedFiles)
        {
            Project.SaveSourceFile(path, text);
            codeFiles[path] = (codeFiles[path].Document, text);
        }

        // Saving moves renamed graphs to new files, which replaces their project entries.
        Graph = Project.Graphs.First(graph => graph.Graph == Graph.Graph);
        foreach (GraphEditor editor in editors.Values)
        {
            editor.MarkSaved();
        }
    }

    private GraphEditor EditorFor(ProjectGraph graph)
    {
        if (!editors.TryGetValue(graph.Graph, out GraphEditor? editor))
        {
            editor = new GraphEditor(graph.Graph, Compiler.Library) { ProjectGraphs = Project.GraphDocuments };
            editor.Changed += (_, _) =>
            {
                versions[graph.Graph] = versions.GetValueOrDefault(graph.Graph) + 1;
                Changed?.Invoke(this, EventArgs.Empty);
            };
            editors.Add(graph.Graph, editor);
        }

        return editor;
    }
}
