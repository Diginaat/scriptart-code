using System.Globalization;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using VisualStudioLikeIDE.Compiler.Ir;
using VisualStudioLikeIDE.Compiler.TypeSystem;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace VisualStudioLikeIDE.Compiler.Emit;

/// <summary>
/// Turns IR into a formatted C# file using Roslyn syntax trees. Output is deterministic: the same IR always yields the same text.
/// </summary>
internal static class CSharpEmitter
{
    private const string NodeAnnotationKind = "VisualStudioLikeIDE.Node";
    private const string Indentation = "    ";
    private const string EndOfLineText = "\n";

    public static GeneratedSource Emit(IrClass irClass, string relativePath, string sourceDescription)
    {
        var usings = new SortedSet<string>(StringComparer.Ordinal);
        MemberDeclarationSyntax[] methods = [.. irClass.Methods.Select(method => EmitMethod(method, usings))];

        ClassDeclarationSyntax classDeclaration = ClassDeclaration(irClass.Name)
            .AddModifiers(irClass.IsPartial
                ? [Token(SyntaxKind.InternalKeyword), Token(SyntaxKind.StaticKeyword), Token(SyntaxKind.PartialKeyword)]
                : [Token(SyntaxKind.InternalKeyword), Token(SyntaxKind.StaticKeyword)])
            .AddMembers(methods);

        CompilationUnitSyntax unit = CompilationUnit()
            .AddUsings([.. usings.Select(name => UsingDirective(ParseName(name)))])
            .AddMembers(FileScopedNamespaceDeclaration(ParseName(irClass.Namespace)).AddMembers(classDeclaration));

        unit = unit.NormalizeWhitespace(Indentation, EndOfLineText);

        // NormalizeWhitespace puts the first type directly under a file-scoped namespace; separate them like hand-written code.
        ClassDeclarationSyntax normalizedClass = unit.DescendantNodes().OfType<ClassDeclarationSyntax>().First();
        unit = unit.ReplaceNode(normalizedClass, normalizedClass.WithLeadingTrivia(normalizedClass.GetLeadingTrivia().Insert(0, EndOfLine(EndOfLineText))));
        unit = unit.WithLeadingTrivia(FileHeader(sourceDescription).AddRange(unit.GetLeadingTrivia()));

        SyntaxTree tree = CSharpSyntaxTree.Create(unit);
        return new GeneratedSource(relativePath, tree.GetText() + EndOfLineText, BuildSourceMap(tree));
    }

    private static SyntaxTriviaList FileHeader(string sourceDescription) => ParseLeadingTrivia(
        "// <auto-generated>" + EndOfLineText +
        $"{GeneratedSource.OwnershipMarker} from {sourceDescription}." + EndOfLineText +
        "//     Changes to this file are overwritten when the graph is compiled." + EndOfLineText +
        "// </auto-generated>" + EndOfLineText + EndOfLineText +
        "#nullable enable" + EndOfLineText + EndOfLineText);

    private static MethodDeclarationSyntax EmitMethod(IrMethod method, SortedSet<string> usings) =>
        MethodDeclaration(TypeSyntaxFor(method.ReturnType), method.Name)
            .AddModifiers(Token(method.IsPrivate ? SyntaxKind.PrivateKeyword : SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword))
            .AddParameterListParameters([.. method.Parameters.Select(parameter =>
                Parameter(Identifier(parameter.Name)).WithType(TypeSyntaxFor(parameter.Type)))])
            .WithBody(EmitBlock(method.Body, usings));

    private static BlockSyntax EmitBlock(IrBlock block, SortedSet<string> usings) =>
        Block(block.Statements.Select(statement => EmitStatement(statement, usings)));

    private static StatementSyntax EmitStatement(IrStatement statement, SortedSet<string> usings)
    {
        StatementSyntax syntax = statement switch
        {
            IrExpressionStatement expression => ExpressionStatement(EmitExpression(expression.Expression, usings)),
            IrLocalDeclaration declaration => LocalDeclarationStatement(VariableDeclaration(
                declaration.Local.Type.Keyword is null ? IdentifierName("var") : TypeSyntaxFor(declaration.Local.Type),
                [VariableDeclarator(declaration.Local.Name).WithInitializer(EqualsValueClause(EmitExpression(declaration.Initializer, usings)))])),
            IrAssignment assignment => ExpressionStatement(AssignmentExpression(
                SyntaxKind.SimpleAssignmentExpression, IdentifierName(assignment.Local.Name), EmitExpression(assignment.Value, usings))),
            IrIf branch => EmitIf(branch, usings),
            IrReturn ret => ReturnStatement(ret.Value is null ? null : EmitExpression(ret.Value, usings)),
            IrWhile loop => WhileStatement(EmitExpression(loop.Condition, usings), EmitBlock(loop.Body, usings)),
            IrFor loop => EmitFor(loop, usings),
            IrBreak => BreakStatement(),
            IrContinue => ContinueStatement(),
            IrThrow thrown => ThrowStatement(ObjectCreationExpression(TypeExpression(TypeRef.InvalidOperationException, usings))
                .WithArgumentList(Arguments([thrown.Message], usings))),
            IrTry attempt => EmitTry(attempt, usings),
            _ => throw new NotSupportedException($"Unsupported IR statement {statement.GetType().Name}."),
        };

        return statement.SourceNodeId is null
            ? syntax
            : syntax.WithAdditionalAnnotations(new SyntaxAnnotation(NodeAnnotationKind, statement.SourceNodeId));
    }

    private static ForStatementSyntax EmitFor(IrFor loop, SortedSet<string> usings)
    {
        // The condition goes through the binary-expression emitter so the end value gets parentheses only when it needs them.
        var condition = new IrBinary(IrBinaryOperator.LessThan, new IrLocalReference(loop.Index), loop.End, TypeRef.Boolean);
        return ForStatement(EmitBlock(loop.Body, usings))
            .WithDeclaration(VariableDeclaration(TypeSyntaxFor(loop.Index.Type),
                [VariableDeclarator(loop.Index.Name).WithInitializer(EqualsValueClause(EmitExpression(loop.Start, usings)))]))
            .WithCondition(EmitExpression(condition, usings))
            .WithIncrementors([PostfixUnaryExpression(SyntaxKind.PostIncrementExpression, IdentifierName(loop.Index.Name))]);
    }

    private static TryStatementSyntax EmitTry(IrTry attempt, SortedSet<string> usings)
    {
        CatchDeclarationSyntax declaration = CatchDeclaration(TypeExpression(TypeRef.Exception, usings));
        if (attempt.Exception is { } exception)
        {
            declaration = declaration.WithIdentifier(Identifier(exception.Name));
        }

        TryStatementSyntax syntax = TryStatement(EmitBlock(attempt.Try, usings), [CatchClause(declaration, null, EmitBlock(attempt.Catch, usings))], null);
        return attempt.Finally.IsEmpty ? syntax : syntax.WithFinally(FinallyClause(EmitBlock(attempt.Finally, usings)));
    }

    private static IfStatementSyntax EmitIf(IrIf branch, SortedSet<string> usings)
    {
        IfStatementSyntax syntax = IfStatement(EmitExpression(branch.Condition, usings), EmitBlock(branch.Then, usings));
        if (branch.Else.IsEmpty)
        {
            return syntax;
        }

        // A lone if inside else reads better as "else if".
        StatementSyntax elseBody = branch.Else.Statements is [IrIf nested]
            ? EmitStatement(nested, usings)
            : EmitBlock(branch.Else, usings);
        return syntax.WithElse(ElseClause(elseBody));
    }

    private static ExpressionSyntax EmitExpression(IrExpression expression, SortedSet<string> usings) => expression switch
    {
        IrLiteral literal => EmitLiteral(literal.Value),
        IrLocalReference local => IdentifierName(local.Local.Name),
        IrBinary binary => EmitBinary(binary, usings),
        IrUnary unary => PrefixUnaryExpression(
            unary.Operator == IrUnaryOperator.LogicalNot ? SyntaxKind.LogicalNotExpression : SyntaxKind.UnaryMinusExpression,
            Operand(unary.Operand, Precedence.Unary, usings, avoidUnaryMinus: unary.Operator == IrUnaryOperator.Negate)),
        IrConvert convert => EmitConvert(convert, usings),
        IrStaticCall call => InvocationExpression(
            MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, TypeExpression(call.DeclaringType, usings), IdentifierName(call.MethodName)),
            Arguments(call.Arguments, usings)),
        IrCall call => InvocationExpression(IdentifierName(call.MethodName), Arguments(call.Arguments, usings)),
        IrInstanceCall call => InvocationExpression(
            MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, Operand(call.Receiver, Precedence.Primary, usings), IdentifierName(call.MethodName)),
            Arguments(call.Arguments, usings)),
        IrMemberAccess access => MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression, Operand(access.Receiver, Precedence.Primary, usings), IdentifierName(access.MemberName)),
        IrError => throw new InvalidOperationException("IR containing errors must not be emitted."),
        _ => throw new NotSupportedException($"Unsupported IR expression {expression.GetType().Name}."),
    };

    private static ExpressionSyntax EmitConvert(IrConvert convert, SortedSet<string> usings)
    {
        if (convert.Type == TypeRef.Double && convert.Operand is IrLiteral { Value: int integer })
        {
            return EmitLiteral((double)integer);
        }

        return CastExpression(TypeSyntaxFor(convert.Type), Operand(convert.Operand, Precedence.Unary, usings, avoidUnaryMinus: false));
    }

    private static ArgumentListSyntax Arguments(IReadOnlyList<IrExpression> arguments, SortedSet<string> usings) =>
        ArgumentList(SeparatedList(arguments.Select(argument => Argument(EmitExpression(argument, usings)))));

    private static BinaryExpressionSyntax EmitBinary(IrBinary binary, SortedSet<string> usings)
    {
        (SyntaxKind kind, Precedence precedence) = binary.Operator switch
        {
            IrBinaryOperator.Add => (SyntaxKind.AddExpression, Precedence.Additive),
            IrBinaryOperator.Subtract => (SyntaxKind.SubtractExpression, Precedence.Additive),
            IrBinaryOperator.Multiply => (SyntaxKind.MultiplyExpression, Precedence.Multiplicative),
            IrBinaryOperator.Divide => (SyntaxKind.DivideExpression, Precedence.Multiplicative),
            IrBinaryOperator.Remainder => (SyntaxKind.ModuloExpression, Precedence.Multiplicative),
            IrBinaryOperator.Equal => (SyntaxKind.EqualsExpression, Precedence.Equality),
            IrBinaryOperator.NotEqual => (SyntaxKind.NotEqualsExpression, Precedence.Equality),
            IrBinaryOperator.LessThan => (SyntaxKind.LessThanExpression, Precedence.Relational),
            IrBinaryOperator.LessThanOrEqual => (SyntaxKind.LessThanOrEqualExpression, Precedence.Relational),
            IrBinaryOperator.GreaterThan => (SyntaxKind.GreaterThanExpression, Precedence.Relational),
            IrBinaryOperator.GreaterThanOrEqual => (SyntaxKind.GreaterThanOrEqualExpression, Precedence.Relational),
            IrBinaryOperator.LogicalAnd => (SyntaxKind.LogicalAndExpression, Precedence.LogicalAnd),
            IrBinaryOperator.LogicalOr => (SyntaxKind.LogicalOrExpression, Precedence.LogicalOr),
            IrBinaryOperator.Coalesce => (SyntaxKind.CoalesceExpression, Precedence.Coalesce),
            _ => throw new NotSupportedException($"Unsupported operator {binary.Operator}."),
        };

        // Left-associative operators need parentheses around an equal-precedence right operand; ?? is right-associative.
        bool rightAssociative = binary.Operator == IrBinaryOperator.Coalesce;
        ExpressionSyntax left = Operand(binary.Left, rightAssociative ? precedence + 1 : precedence, usings);
        ExpressionSyntax right = Operand(binary.Right, rightAssociative ? precedence : precedence + 1, usings);
        return BinaryExpression(kind, left, right);
    }

    /// <summary>Emits an operand, adding parentheses when its precedence is lower than <paramref name="required"/>.</summary>
    private static ExpressionSyntax Operand(IrExpression operand, Precedence required, SortedSet<string> usings, bool avoidUnaryMinus = false)
    {
        ExpressionSyntax syntax = EmitExpression(operand, usings);
        bool startsWithMinus = syntax is PrefixUnaryExpressionSyntax { RawKind: (int)SyntaxKind.UnaryMinusExpression };
        return PrecedenceOf(operand) < required || (avoidUnaryMinus && startsWithMinus)
            ? ParenthesizedExpression(syntax)
            : syntax;
    }

    private static Precedence PrecedenceOf(IrExpression expression) => expression switch
    {
        IrBinary { Operator: IrBinaryOperator.Multiply or IrBinaryOperator.Divide or IrBinaryOperator.Remainder } => Precedence.Multiplicative,
        IrBinary { Operator: IrBinaryOperator.Add or IrBinaryOperator.Subtract } => Precedence.Additive,
        IrBinary { Operator: IrBinaryOperator.LessThan or IrBinaryOperator.LessThanOrEqual or IrBinaryOperator.GreaterThan or IrBinaryOperator.GreaterThanOrEqual } => Precedence.Relational,
        IrBinary { Operator: IrBinaryOperator.Equal or IrBinaryOperator.NotEqual } => Precedence.Equality,
        IrBinary { Operator: IrBinaryOperator.LogicalAnd } => Precedence.LogicalAnd,
        IrBinary { Operator: IrBinaryOperator.LogicalOr } => Precedence.LogicalOr,
        IrBinary { Operator: IrBinaryOperator.Coalesce } => Precedence.Coalesce,
        IrUnary or IrConvert => Precedence.Unary,
        IrLiteral { Value: int and < 0 } or IrLiteral { Value: double and < 0 } => Precedence.Unary,
        _ => Precedence.Primary,
    };

    private static ExpressionSyntax EmitLiteral(object value) => value switch
    {
        string text => LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(text)),
        bool boolean => LiteralExpression(boolean ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression),
        int integer when integer < 0 => PrefixUnaryExpression(SyntaxKind.UnaryMinusExpression,
            LiteralExpression(SyntaxKind.NumericLiteralExpression, NegatedIntegerLiteral(integer))),
        int integer => LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(integer)),
        double number when number < 0 || double.IsNegative(number) => PrefixUnaryExpression(SyntaxKind.UnaryMinusExpression, EmitLiteral(-number)),
        double number => LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(DoubleText(number), number)),
        _ => throw new NotSupportedException($"Unsupported literal type {value.GetType().Name}."),
    };

    /// <summary>The magnitude of a negative integer. Works for <see cref="int.MinValue"/>, whose magnitude does not fit in an int.</summary>
    private static SyntaxToken NegatedIntegerLiteral(int integer)
    {
        uint magnitude = (uint)-(long)integer;
        return Literal(magnitude.ToString(CultureInfo.InvariantCulture), magnitude);
    }

    /// <summary>Round-trippable text that the C# lexer reads as a double, for example <c>2.0</c> rather than <c>2</c>.</summary>
    private static string DoubleText(double number)
    {
        string text = number.ToString("R", CultureInfo.InvariantCulture);
        return text.Contains('.', StringComparison.Ordinal) || text.Contains('E', StringComparison.Ordinal) ? text : text + ".0";
    }

    private static TypeSyntax TypeSyntaxFor(TypeRef type) => type.Keyword switch
    {
        "void" => PredefinedType(Token(SyntaxKind.VoidKeyword)),
        "bool" => PredefinedType(Token(SyntaxKind.BoolKeyword)),
        "int" => PredefinedType(Token(SyntaxKind.IntKeyword)),
        "double" => PredefinedType(Token(SyntaxKind.DoubleKeyword)),
        "string" => PredefinedType(Token(SyntaxKind.StringKeyword)),
        _ => IdentifierName(type.Name),
    };

    private static TypeSyntax TypeExpression(TypeRef type, SortedSet<string> usings)
    {
        if (type.Keyword is null)
        {
            usings.Add(type.Namespace);
        }

        return TypeSyntaxFor(type);
    }

    private static List<SourceMapEntry> BuildSourceMap(SyntaxTree tree)
    {
        List<SourceMapEntry> entries = [];
        foreach (SyntaxNode node in tree.GetRoot().GetAnnotatedNodes(NodeAnnotationKind))
        {
            string nodeId = node.GetAnnotations(NodeAnnotationKind).First().Data!;
            FileLinePositionSpan span = tree.GetLineSpan(node.Span);
            entries.Add(new SourceMapEntry(nodeId, span.StartLinePosition.Line + 1, span.EndLinePosition.Line + 1));
        }

        return entries;
    }

    private enum Precedence
    {
        Coalesce,
        LogicalOr,
        LogicalAnd,
        Equality,
        Relational,
        Additive,
        Multiplicative,
        Unary,
        Primary,
    }
}
