namespace VisualStudioLikeIDE.Compiler.Emit;

/// <summary>Lines of generated code produced by one graph node. Lines are one-based and inclusive.</summary>
public sealed record SourceMapEntry(string NodeId, int StartLine, int EndLine);

/// <summary>A generated C# file and the mapping from graph nodes to its lines.</summary>
/// <param name="RelativePath">Path relative to the project's generated-code folder, for example <c>Program.g.cs</c>.</param>
public sealed record GeneratedSource(string RelativePath, string Text, IReadOnlyList<SourceMapEntry> SourceMap)
{
    /// <summary>
    /// The second line of every generated file. A file is owned by the generator, and may be overwritten or deleted by it,
    /// only when it starts with this header.
    /// </summary>
    public const string OwnershipMarker = "//     Generated by VisualStudioLikeIDE";

    /// <summary>True when <paramref name="fileText"/> was produced by this generator.</summary>
    public static bool IsGeneratedText(string fileText)
    {
        ArgumentNullException.ThrowIfNull(fileText);
        string[] lines = fileText.Split('\n', 3);
        return lines.Length >= 2
            && lines[0].TrimEnd('\r') == "// <auto-generated>"
            && lines[1].StartsWith(OwnershipMarker, StringComparison.Ordinal);
    }

    /// <summary>The first line generated for a node, or null when the node generated no code.</summary>
    public SourceMapEntry? FindNode(string nodeId) => SourceMap.FirstOrDefault(entry => entry.NodeId == nodeId);

    /// <summary>The innermost node whose generated code contains <paramref name="line"/>.</summary>
    public SourceMapEntry? FindLine(int line) => SourceMap
        .Where(entry => entry.StartLine <= line && line <= entry.EndLine)
        .MinBy(entry => entry.EndLine - entry.StartLine);
}
