using VisualStudioLikeIDE.Compiler.Diagnostics;
using VisualStudioLikeIDE.Compiler.Emit;
using VisualStudioLikeIDE.GraphModel;

namespace VisualStudioLikeIDE.ProjectSystem;

/// <summary>
/// Writes generated sources into the project's generated-code folder while enforcing the ownership model:
/// only files that carry the generator's header are ever overwritten or deleted. See docs/CODE_GENERATION.md.
/// </summary>
public static class GeneratedFileWriter
{
    public const string OwnershipConflictId = "VSP0001";

    /// <summary>
    /// Writes <paramref name="sources"/> to <paramref name="directory"/>. Nothing is written when any target is a handwritten file.
    /// Unchanged files are not rewritten, so builds stay incremental.
    /// </summary>
    /// <returns>Diagnostics for ownership conflicts; empty on success.</returns>
    public static IReadOnlyList<GraphDiagnostic> Write(string directory, IReadOnlyList<GeneratedSource> sources, out IReadOnlyList<string> changedFiles)
    {
        ArgumentNullException.ThrowIfNull(sources);
        List<GraphDiagnostic> conflicts = [];
        foreach (GeneratedSource source in sources)
        {
            string path = Path.Combine(directory, source.RelativePath);
            if (File.Exists(path) && !GeneratedSource.IsGeneratedText(File.ReadAllText(path)))
            {
                conflicts.Add(new GraphDiagnostic(OwnershipConflictId, DiagnosticSeverity.Error,
                    $"'{path}' exists but was not generated by VisualStudioLikeIDE. Rename or move it; it will not be overwritten.",
                    FilePath: path));
            }
        }

        List<string> changed = [];
        changedFiles = changed;
        if (conflicts.Count > 0)
        {
            return conflicts;
        }

        Directory.CreateDirectory(directory);
        var expected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (GeneratedSource source in sources)
        {
            string path = Path.GetFullPath(Path.Combine(directory, source.RelativePath));
            expected.Add(path);
            if (!File.Exists(path) || File.ReadAllText(path) != source.Text)
            {
                AtomicFile.WriteAllText(path, source.Text);
                changed.Add(path);
            }
        }

        // Remove generated files whose graph no longer exists. Handwritten files in the folder are left alone.
        foreach (string path in Directory.EnumerateFiles(directory, "*.cs"))
        {
            string fullPath = Path.GetFullPath(path);
            if (!expected.Contains(fullPath) && GeneratedSource.IsGeneratedText(File.ReadAllText(fullPath)))
            {
                File.Delete(fullPath);
                changed.Add(fullPath);
            }
        }

        return [];
    }
}
