    [Fact]
    public async Task NewProjectRequestsAreRefusedBeforeRunningDotnet()
    {
        using var directory = new TemporaryDirectory();
        string folder = Path.Combine(directory.Path, "Hello");
        Directory.CreateDirectory(folder);
        VisualProject project = VisualProject.Create(folder, "Hello");
        string solution = Path.Combine(folder, "Hello.slnx");
        Directory.CreateDirectory(Path.Combine(directory.Path, "Taken"));

        await Assert.ThrowsAsync<ArgumentException>(() => ProjectSolution.NewProjectAsync(project, solution, "web", "Shapes", false, _ => { }, CancellationToken.None));
        await Assert.ThrowsAsync<ArgumentException>(() => ProjectSolution.NewProjectAsync(project, solution, "classlib", "--output", false, _ => { }, CancellationToken.None));
        await Assert.ThrowsAsync<IOException>(() => ProjectSolution.NewProjectAsync(project, solution, "classlib", "Taken", false, _ => { }, CancellationToken.None));
        await Assert.ThrowsAsync<ArgumentException>(() => ProjectSolution.AddToSolutionAsync(solution, Path.Combine(directory.Path, "none.csproj"), _ => { }, CancellationToken.None));
    }

    [Fact]
    public void RestoreIsNeededOnlyForUnrestoredOrChangedPackages()
    {
        using var directory = new TemporaryDirectory();
        string csproj = Path.Combine(directory.Path, "App.csproj");
        File.WriteAllText(csproj, "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup></Project>");
        Assert.False(ProjectReferences.NeedsRestore(csproj));

        File.WriteAllText(csproj, """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup>
              <ItemGroup><PackageReference Include="Humanizer" Version="2.14.1" /></ItemGroup>
            </Project>
            """);
        Assert.True(ProjectReferences.NeedsRestore(csproj));
    }

    [Theory]
    [InlineData("script.vside")]
