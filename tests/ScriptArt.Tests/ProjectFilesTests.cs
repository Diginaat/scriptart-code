/// <summary>The Explorer's file management: what it lists, what it refuses, and how it finds VS Code and solution projects (D-043).</summary>
public sealed class ProjectFilesTests
{
    private const string GeneratedHeader = "// <auto-generated>\n" + GeneratedSource.OwnershipMarker + "\n// </auto-generated>\n";

    [Fact]
    public void FilesAreClassifiedAndBuildOutputIsHidden()
    {
        using var directory = new TemporaryDirectory();
        VisualProject project = VisualProject.Create(directory.Path, "Hello");
        string generated = Path.Combine(directory.Path, "Generated", "Program.g.cs");
        Directory.CreateDirectory(Path.GetDirectoryName(generated)!);
        File.WriteAllText(generated, GeneratedHeader + "class Program {}");
        string handwritten = Path.Combine(directory.Path, "Helpers.cs");
        File.WriteAllText(handwritten, "class Helpers {}");
        string notes = Path.Combine(directory.Path, "notes.txt");
        File.WriteAllText(notes, "hello");
        string blob = Path.Combine(directory.Path, "data.bin");
        File.WriteAllBytes(blob, [1, 0, 2]);
        Directory.CreateDirectory(Path.Combine(directory.Path, "obj"));
        File.WriteAllText(Path.Combine(directory.Path, "obj", "project.assets.json"), "{}");

        Assert.Equal(ProjectFileKind.ProjectFile, ProjectFiles.KindOf(project, project.ProjectFilePath));
        Assert.Equal(ProjectFileKind.Graph, ProjectFiles.KindOf(project, Path.Combine(directory.Path, project.Graphs[0].RelativePath)));
        Assert.Equal(ProjectFileKind.Generated, ProjectFiles.KindOf(project, generated));
        Assert.Equal(ProjectFileKind.CSharp, ProjectFiles.KindOf(project, handwritten));
        Assert.Equal(ProjectFileKind.Text, ProjectFiles.KindOf(project, notes));
        Assert.Equal(ProjectFileKind.Text, ProjectFiles.KindOf(project, project.CsprojPath));
        Assert.Equal(ProjectFileKind.Binary, ProjectFiles.KindOf(project, blob));

        IReadOnlyList<ProjectFileEntry> top = ProjectFiles.List(directory.Path);
        Assert.DoesNotContain(top, entry => entry.Name == "obj");
        Assert.True(top.TakeWhile(entry => entry.IsDirectory).Count() == top.Count(entry => entry.IsDirectory), "Folders come before files.");
        IReadOnlyList<string> all = ProjectFiles.ListAll(directory.Path);
        Assert.Contains(generated, all);
        Assert.DoesNotContain(all, path => path.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}", StringComparison.Ordinal));
    }

    [Fact]
    public void ManagedFilesAreProtected()
    {
        using var directory = new TemporaryDirectory();
        VisualProject project = VisualProject.Create(directory.Path, "Hello");
        string graph = Path.Combine(directory.Path, project.Graphs[0].RelativePath);
        string graphsFolder = Path.GetDirectoryName(graph)!;
        string generated = Path.Combine(directory.Path, "Generated", "Program.g.cs");
        Directory.CreateDirectory(Path.GetDirectoryName(generated)!);
        File.WriteAllText(generated, GeneratedHeader);
        string free = Path.Combine(directory.Path, "Docs");
        Directory.CreateDirectory(free);

        Assert.NotNull(ProjectFiles.ProtectionOf(project, directory.Path));
        Assert.NotNull(ProjectFiles.ProtectionOf(project, project.ProjectFilePath));
        Assert.NotNull(ProjectFiles.ProtectionOf(project, project.CsprojPath));
        Assert.NotNull(ProjectFiles.ProtectionOf(project, graph));
        Assert.NotNull(ProjectFiles.ProtectionOf(project, graphsFolder));
        Assert.NotNull(ProjectFiles.ProtectionOf(project, generated));
        Assert.Null(ProjectFiles.ProtectionOf(project, free));

        Assert.Throws<InvalidOperationException>(() => ProjectFiles.Delete(project, graph));
        Assert.Throws<InvalidOperationException>(() => ProjectFiles.Rename(project, generated, "Other.cs"));
        Assert.Throws<InvalidOperationException>(() => ProjectFiles.SaveText(project, generated, "class X {}"));
        Assert.Throws<InvalidOperationException>(() => ProjectFiles.SaveText(project, project.ProjectFilePath, "{}"));
        Assert.True(File.Exists(graph));
        Assert.Equal(GeneratedHeader, File.ReadAllText(generated));
    }

    [Fact]
    public void FilesAreCreatedRenamedSavedAndDeletedInsideTheProject()
    {
        using var directory = new TemporaryDirectory();
        VisualProject project = VisualProject.Create(directory.Path, "Hello");

        string folder = ProjectFiles.CreateFolder(project, directory.Path, "Docs");
        string readme = ProjectFiles.CreateFile(project, folder, "readme.md");
        string code = ProjectFiles.CreateFile(project, directory.Path, "Shapes.cs");
        ProjectFiles.SaveText(project, readme, "# Hello");
        string renamed = ProjectFiles.Rename(project, folder, "Notes");

        Assert.Equal($"namespace {project.Document.RootNamespace};\n", File.ReadAllText(code));
        Assert.Equal("# Hello", File.ReadAllText(Path.Combine(renamed, "readme.md")));
        Assert.Throws<IOException>(() => ProjectFiles.CreateFile(project, directory.Path, "Shapes.cs"));
        Assert.Throws<ArgumentException>(() => ProjectFiles.CreateFile(project, directory.Path, "../escape.txt"));
        Assert.Throws<ArgumentException>(() => ProjectFiles.CreateFile(project, Path.GetDirectoryName(directory.Path)!, "outside.txt"));
        Assert.Throws<ArgumentException>(() => ProjectFiles.Delete(project, Path.Combine(directory.Path, "..", "elsewhere")));
        Assert.Throws<InvalidOperationException>(() => ProjectFiles.SaveText(project, Path.Combine(renamed, "readme.md"), GeneratedHeader));

        ProjectFiles.Delete(project, renamed);
        Assert.False(Directory.Exists(renamed));
    }

