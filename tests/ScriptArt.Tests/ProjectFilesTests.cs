    [Fact]
    public void VisualStudioCodeIsFoundFromTheOverridePathAndDefaults()
    {
        HashSet<string> existing = new(StringComparer.OrdinalIgnoreCase);
        bool Exists(string path) => existing.Contains(path);
        string install = Path.Combine("C:", "Tools", "Microsoft VS Code");
        string bin = Path.Combine(install, "bin");
        string unixBin = Path.Combine("/opt", "code", "bin");

        Assert.Null(VisualStudioCode.Find(null, bin, windows: true, Exists));

        existing.Add(Path.Combine(bin, "code.cmd"));
        existing.Add(Path.Combine(install, "Code.exe"));
        Assert.Equal(Path.Combine(install, "Code.exe"), VisualStudioCode.Find(null, bin, windows: true, Exists));

        existing.Add(Path.Combine(unixBin, "code"));
        Assert.Equal(Path.Combine(unixBin, "code"), VisualStudioCode.Find("", unixBin, windows: false, Exists));

        existing.Add("custom-code");
        Assert.Equal("custom-code", VisualStudioCode.Find("custom-code", bin, windows: true, Exists));
        Assert.Equal(Path.Combine(install, "Code.exe"), VisualStudioCode.Find("missing-code", bin, windows: true, Exists));
    }

    [Fact]
    public void SolutionProjectsAreReadFromSlnxAndSln()
    {
        using var directory = new TemporaryDirectory();
        string slnx = Path.Combine(directory.Path, "All.slnx");
        File.WriteAllText(slnx, """
            <Solution>
              <Folder Name="/src/">
                <Project Path="src/App/App.csproj" />
              </Folder>
              <Project Path="Lib\Lib.csproj" />
            </Solution>
            """);
        string sln = Path.Combine(directory.Path, "All.sln");
        File.WriteAllText(sln, """
            Microsoft Visual Studio Solution File, Format Version 12.00
            Project("{FAE04EC0-301F-11D3-BF4B-00C04F79EFBC}") = "App", "src\App\App.csproj", "{11111111-1111-1111-1111-111111111111}"
            EndProject
            Project("{2150E333-8FDC-42A3-9474-1A3956D46DE8}") = "src", "src", "{22222222-2222-2222-2222-222222222222}"
            EndProject
            """);
        string app = Path.Combine(directory.Path, "src", "App", "App.csproj");
        string lib = Path.Combine(directory.Path, "Lib", "Lib.csproj");

        Assert.Equal([app, lib], ProjectSolution.ProjectsIn(slnx));
        Assert.Equal([app], ProjectSolution.ProjectsIn(sln));
        Assert.Empty(ProjectSolution.ProjectsIn(Path.Combine(directory.Path, "Missing.slnx")));
    }

